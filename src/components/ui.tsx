export function Icon({ name, className = 'w-[18px] h-[18px]' }: { name: string; className?: string }) {
  return (
    <svg className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round"
      dangerouslySetInnerHTML={{ __html: ICONS[name] }} />
  )
}

export function Avatar({ name, className = 'w-9 h-9 bg-indigo-100 text-indigo-700' }: { name: string; className?: string }) {
  return <span className={`rounded-full flex items-center justify-center font-semibold shrink-0 ${className}`}>{initial(name)}</span>
}

export function Modal({ open, onClose, children, maxW = 'md:max-w-md' }: { open: boolean; onClose: () => void; children: ReactNode; maxW?: string }) {
  useEffect(() => {
    if (!open) return
    const h = (e: KeyboardEvent) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', h)
    return () => window.removeEventListener('keydown', h)
  }, [open, onClose])
  if (!open) return null
  return (
    <div className="fixed inset-0 bg-black/40 z-40 flex items-end md:items-center justify-center no-print" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`bg-white w-full ${maxW} rounded-t-xl md:rounded-xl p-4 max-h-[92vh] overflow-y-auto`}>{children}</div>
    </div>
  )
}

export function Empty({ children, icon }: { children: ReactNode; icon?: string }) {
  return (
    <div className="bg-white rounded-lg shadow-sm p-10 text-center text-slate-400">
      {icon && <div className="text-3xl mb-2">{icon}</div>}{children}
    </div>
  )
}

export function PageTitle({ children, sub }: { children: ReactNode; sub?: ReactNode }) {
  return <h1 className="page-title mb-3">{children} {sub && <span className="text-slate-400 font-normal text-sm">{sub}</span>}</h1>
}

export function Tabs<T extends string>({ value, onChange, tabs, right }: { value: T; onChange: (v: T) => void; tabs: [T, string][]; right?: ReactNode }) {
  return (
    <div className="flex items-center gap-1 mb-3 border-b">
      {tabs.map(([id, label]) => (
        <button key={id} className={`px-4 py-2 -mb-px border-b-2 ${value === id ? 'border-indigo-600 text-indigo-700 font-semibold' : 'border-transparent text-slate-500'}`} onClick={() => onChange(id)}>{label}</button>
      ))}
      {right && <div className="ml-auto mb-1">{right}</div>}
    </div>
  )
}

export function Forbidden() {
  return <Empty icon="🔒">Bạn không có quyền xem trang này.</Empty>
}

export function Loading({ error }: { error?: unknown }) {
  if (error) return <Empty icon="⚠️">Không tải được dữ liệu: {(error as { message?: string }).message ?? 'lỗi không xác định'}</Empty>
  return <div className="p-8 text-slate-400">Đang tải…</div>
}
